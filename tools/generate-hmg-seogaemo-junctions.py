#!/usr/bin/env python3
"""Compile the local, observed PE14 CSVs; no dataset is shipped in the repository."""
import argparse
import csv
import hashlib
from pathlib import Path

LAYOUTS = ['exit_left', 'exit_right', 'fork_left', 'fork_right', 'other',
           'Y', 'Y_pocket', 'loop_right', 'multi']
ROUTES = ['straight', 'exit', 'left_branch', 'right_branch', 'main_curve', 'lane_variant']
SIDES = {'L': -1, '-': 0, 'R': 1, 'both': 0}
DEFAULT = Path('modules/wireless-carplay-and-aa/payload/src/hmgapi/mods/wireless/dipo/CpJunctionTable.java.src')


def rows(path, required):
    with path.open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream)
        if not set(required).issubset(reader.fieldnames or []):
            raise ValueError(str(path) + ': missing CSV columns')
        return list(reader)


def generate(table, highlights):
    pictures = sorted(rows(table, ['A', 'layout', 'lanes', 'branch_side',
                                  'B_straight', 'B_exit', 'B_left', 'B_right']),
                      key=lambda row: int(row['A']))
    bs = sorted(rows(highlights, ['B', 'A', 'road', 'route', 'side', 'lanes']),
                key=lambda row: int(row['B']))
    by_a, seen_b, p_data, b_data = {}, set(), [], []
    for index, row in enumerate(pictures):
        a, lanes = int(row['A']), int(row['lanes'])
        if a in by_a or not 10001 <= a <= 11011 or not 1 <= lanes <= 8:
            raise ValueError('invalid/duplicate picture: ' + str(a))
        by_a[a] = (index, row)
        p_data.append([a, LAYOUTS.index(row['layout']), lanes, SIDES[row['branch_side']]])
    for row in bs:
        b, a = int(row['B']), int(row['A'])
        if b in seen_b or not 10001 <= b <= 11015:
            raise ValueError('invalid/duplicate highlight: ' + str(b))
        seen_b.add(b)
        index, picture = by_a[a]
        if row['lanes'] != picture['lanes']:
            raise ValueError('inconsistent lane count: ' + str(b))
        preferred = str(b) in [picture[k] for k in ('B_straight', 'B_exit', 'B_left', 'B_right')]
        b_data.append([index, b, ROUTES.index(row['route']), SIDES[row['side']], int(preferred)])
    for _, row in by_a.values():
        for key in ('B_straight', 'B_exit', 'B_left', 'B_right'):
            if row[key] and not any(r['B'] == row[key] and r['A'] == row['A'] for r in bs):
                raise ValueError('missing declared highlight: ' + row[key])
    digest = hashlib.sha256(table.read_bytes() + b'\0' + highlights.read_bytes()).hexdigest()
    out = ['package hmgapi.mods.wireless.dipo;', '',
           '// Generated by tools/generate-hmg-seogaemo-junctions.py; do not edit.',
           '// Source: hud-junction-pe14/sweep/groups/{table,b_table}.csv (observed stock pictures).',
           '// CSV SHA-256: ' + digest,
           '// Picture: A, layout, lane count, branch side (-1 left / 0 both / 1 right).',
           '// Highlight: picture index, B, route, side, preferred in picture table.',
           '// lane_variant is retained as evidence, never promoted to a route.',
           'final class CpJunctionTable {']
    for name, values in [('LAYOUT', LAYOUTS), ('ROUTE', ROUTES)]:
        out.extend('    static final int %s_%s = %d;' % (name, value.upper(), i)
                   for i, value in enumerate(values))
    for name, data in [('PICTURES', p_data), ('HIGHLIGHTS', b_data)]:
        out.append('    static final short[] ' + name + ' = new short[] {')
        # One row per observation; primitive arrays keep the Dalvik footprint small.
        out.extend('        ' + ','.join(map(str, row)) + ',' for row in data)
        out.append('    };')
    out.extend(['    private CpJunctionTable() {}', '}', ''])
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--table', type=Path, required=True)
    parser.add_argument('--b-table', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=DEFAULT)
    args = parser.parse_args()
    try:
        result = generate(args.table, args.b_table)
    except (ValueError, KeyError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result, encoding='utf-8')


if __name__ == '__main__':
    main()
